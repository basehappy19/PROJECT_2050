/* Build the web version of Project : 2050 into the repository root:
     index.html · sw.js · assets/app-[hash].js · assets/app-[hash].css · assets/{img,audio,data,fonts}/…
   The game rules, data and server client are shared with the GDevelop version (gdevelop/_source/src/1x-, 20-, 21-*.js).
   Usage: node build.mjs            (production build)
          node build.mjs --watch    (rebuild on change + local server on http://localhost:5173)
          P2050_API=https://… node build.mjs   (bake a game-server address into index.html) */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import {fileURLToPath} from "node:url";
import * as esbuild from "esbuild";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..");
const SHARED = path.join(REPO, "gdevelop/_source/src");
const OUT = REPO;                       // the site is served from the repository root (GitHub Pages)
const ASSETS = path.join(OUT, "assets");
const WATCH = process.argv.includes("--watch");
const VERSION = JSON.parse(fs.readFileSync(path.join(HERE, "package.json"), "utf8")).version || "3.0.0";

/* ---------- 1. shared engine: wrap each GDevelop module in a function so their top-level "return" guards work ---------- */
function writeEngine(){
  const files = fs.readdirSync(SHARED).filter(f => /^(1\d|20|21)-.*\.js$/.test(f)).sort();
  let code = "/* generated by build.mjs from gdevelop/_source/src — do not edit */\n";
  for (const f of files) code += `\n/* ---- ${f} ---- */\n(function(){\n${fs.readFileSync(path.join(SHARED, f), "utf8")}\n})();\n`;
  code += "\nexport default window.P2050;\n";
  fs.mkdirSync(path.join(HERE, "src/gen"), {recursive:true});
  fs.writeFileSync(path.join(HERE, "src/gen/engine.js"), code);
  return files;
}

/* ---------- 2. icons: only the lucide icons the game uses ---------- */
function writeIcons(){
  const dir = path.join(HERE, "node_modules/lucide-static/icons");
  const avail = new Set(fs.readdirSync(dir).map(f => f.replace(/\.svg$/, "")));
  const used = new Set();
  const scan = txt => { for (const m of txt.matchAll(/["'`\[ ]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`\]]/g)) if (avail.has(m[1])) used.add(m[1]); };
  for (const f of fs.readdirSync(SHARED)) if (f.endsWith(".js")) scan(fs.readFileSync(path.join(SHARED, f), "utf8"));
  const walk = d => { for (const f of fs.readdirSync(d, {withFileTypes:true})){ const p = path.join(d, f.name); if (f.isDirectory()){ if (f.name !== "gen") walk(p); } else if (/\.(jsx?|mjs)$/.test(f.name)) scan(fs.readFileSync(p, "utf8")); } };
  walk(path.join(HERE, "src"));
  const out = {};
  for (const n of [...used].sort()){
    const svg = fs.readFileSync(path.join(dir, n + ".svg"), "utf8");
    out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
  }
  fs.writeFileSync(path.join(HERE, "src/gen/icons.js"), "/* generated by build.mjs (lucide-static, ISC licence) */\nexport default " + JSON.stringify(out) + ";\n");
  return used.size;
}

/* ---------- 3. static media (images, audio, data) live directly in ../assets/; only fonts are copied in ---------- */
function copyDir(src, dst){
  fs.mkdirSync(dst, {recursive:true});
  for (const f of fs.readdirSync(src, {withFileTypes:true})){
    const s = path.join(src, f.name), d = path.join(dst, f.name);
    if (f.isDirectory()) copyDir(s, d);
    else if (!fs.existsSync(d) || fs.statSync(d).mtimeMs < fs.statSync(s).mtimeMs || fs.statSync(d).size !== fs.statSync(s).size) fs.copyFileSync(s, d);
  }
}
function fonts(){
  const dst = path.join(ASSETS, "fonts"); fs.mkdirSync(dst, {recursive:true});
  const pick = [
    ["kanit", "kanit", [500, 600, 700]],
    ["ibm-plex-sans-thai", "ibm-plex-sans-thai", [400, 600]],
    ["ibm-plex-mono", "ibm-plex-mono", [500, 600]],
    ["chakra-petch", "chakra-petch", [600, 700]],
  ];
  let css = "";
  const FAM = {"kanit":"Kanit", "ibm-plex-sans-thai":"IBM Plex Sans Thai", "ibm-plex-mono":"IBM Plex Mono", "chakra-petch":"Chakra Petch"};
  const RANGES = {thai:"U+02D7, U+0303, U+0331, U+0E01-0E5B, U+200C-200D, U+25CC", latin:"U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD"};
  for (const [pkg, file, weights] of pick){
    for (const w of weights) for (const sub of ["thai", "latin"]){
      const src = path.join(HERE, `node_modules/@fontsource/${pkg}/files/${file}-${sub}-${w}-normal.woff2`);
      if (!fs.existsSync(src)) continue;
      const name = `${file}-${sub}-${w}.woff2`;
      fs.copyFileSync(src, path.join(dst, name));
      css += `@font-face{font-family:"${FAM[pkg]}";font-style:normal;font-weight:${w};font-display:swap;src:url(fonts/${name}) format("woff2");unicode-range:${RANGES[sub]};}\n`;
    }
  }
  return css;
}

const hash = buf => crypto.createHash("sha1").update(buf).digest("hex").slice(0, 10);

async function build(){
  const t0 = Date.now();
  const files = writeEngine(), nIcons = writeIcons();
  const fontCss = fonts();
  const res = await esbuild.build({
    entryPoints:[path.join(HERE, "src/main.jsx")], bundle:true, minify:!WATCH, sourcemap:WATCH ? "inline" : false,
    format:"esm", target:["es2020", "safari14"], write:false, outdir:ASSETS, jsx:"automatic", jsxImportSource:"preact",
    loader:{".js":"jsx"}, define:{"process.env.NODE_ENV":WATCH ? '"development"' : '"production"', __VERSION__:JSON.stringify(VERSION)}, legalComments:"none",
  });
  // clean old bundles
  for (const f of fs.readdirSync(ASSETS)) if (/^app-[0-9a-f]+\.(js|css)$/.test(f)) fs.unlinkSync(path.join(ASSETS, f));
  let jsName = "", cssName = "";
  for (const o of res.outputFiles){
    if (o.path.endsWith(".js")){ jsName = `app-${hash(o.contents)}.js`; fs.writeFileSync(path.join(ASSETS, jsName), o.contents); }
    if (o.path.endsWith(".css")){ const c = fontCss + o.text; cssName = `app-${hash(c)}.css`; fs.writeFileSync(path.join(ASSETS, cssName), c); }
  }
  // index.html
  let html = fs.readFileSync(path.join(HERE, "index.html"), "utf8");
  const api = process.env.P2050_API ? `<script>window.P2050_API=${JSON.stringify(process.env.P2050_API)}</script>\n` : "";
  html = html.replace("<!--CSS-->", `<link rel="stylesheet" href="assets/${cssName}">`).replace("<!--JS-->", `${api}<script type="module" src="assets/${jsName}"></script>`).replace(/__VERSION__/g, VERSION);
  fs.writeFileSync(path.join(OUT, "index.html"), html);
  // service worker: precache the shell; big media is cached when first used
  const core = ["./", "index.html", "site.webmanifest", `assets/${jsName}`, `assets/${cssName}`, "assets/data/world.json",
    ...fs.readdirSync(path.join(ASSETS, "fonts")).map(f => `assets/fonts/${f}`)];
  let sw = fs.readFileSync(path.join(HERE, "sw.js"), "utf8");
  sw = sw.replace("/*CORE*/[]", JSON.stringify(core)).replace("__CACHE__", `p2050-web-${hash(core.join() + jsName + cssName)}`);
  fs.writeFileSync(path.join(OUT, "sw.js"), sw);
  console.log(`built ${jsName} (${(fs.statSync(path.join(ASSETS, jsName)).size / 1024).toFixed(0)} KB) ${cssName} · ${files.length} shared modules · ${nIcons} icons · ${Date.now() - t0} ms`);
}

await build();
if (WATCH){
  const http = await import("node:http");
  const TYPES = {".html":"text/html; charset=utf-8", ".js":"text/javascript", ".css":"text/css", ".json":"application/json", ".jpg":"image/jpeg", ".png":"image/png", ".webp":"image/webp", ".svg":"image/svg+xml", ".mp3":"audio/mpeg", ".woff2":"font/woff2", ".webmanifest":"application/manifest+json"};
  http.createServer((req, res) => {
    let p = decodeURIComponent(req.url.split("?")[0]); if (p.endsWith("/")) p += "index.html";
    const f = path.join(OUT, p);
    if (!f.startsWith(OUT) || !fs.existsSync(f)){ res.writeHead(404); return res.end("not found"); }
    res.writeHead(200, {"Content-Type":TYPES[path.extname(f)] || "application/octet-stream", "Cache-Control":"no-store"});
    fs.createReadStream(f).pipe(res);
  }).listen(5173, () => console.log("http://localhost:5173"));
  let timer = null;
  for (const d of [path.join(HERE, "src"), SHARED, path.join(HERE, "index.html")])
    fs.watch(d, {recursive:true}, (e, f) => { if (f && String(f).includes("gen")) return; clearTimeout(timer); timer = setTimeout(() => build().catch(err => console.error(err.message)), 150); });
}
