/* ---------- protection: make the shipped code hard to read and re-use ---------- */
async function obfuscate(code){
  const {default:JO} = await import("javascript-obfuscator");
  return JO.obfuscate(code, {
    target:"browser", compact:true, sourceMap:false, seed:7,
    identifierNamesGenerator:"mangled-shuffled", renameGlobals:false,
    stringArray:true, stringArrayThreshold:.6, stringArrayEncoding:[], stringArrayRotate:true, stringArrayShuffle:true,
    stringArrayIndexShift:true, stringArrayWrappersCount:1, stringArrayWrappersType:"variable",
    controlFlowFlattening:false, deadCodeInjection:false, transformObjectKeys:false, numbersToExpressions:false, splitStrings:false,
    selfDefending:false, debugProtection:false, disableConsoleOutput:false, unicodeEscapeSequence:false,
    domainLock:DOMAINS.length ? [...DOMAINS, "localhost", "127.0.0.1"] : [], domainLockRedirectUrl:"about:blank",
  }).getObfuscatedCode();
}


