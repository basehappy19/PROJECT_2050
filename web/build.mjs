/* Build the web version of Project Zero into the repository root:
     index.html · sw.js · assets/app-[hash].js · assets/app-[hash].css · assets/{img,audio,data,fonts}/…
   The game rules, data and server client are shared with the GDevelop version (gdevelop/_source/src/1x-, 20-, 21-*.js).
   Usage: node build.mjs            (production build)
          node build.mjs --watch    (rebuild on change + local server on http://localhost:5173)
          node build.mjs --open     (readable build: no obfuscation, window.P2050 stays reachable — for tools/scene.mjs, tools/perf.mjs)
          P2050_API=https://… node build.mjs   (bake a game-server address into index.html)
          P2050_DOMAINS=game.example.ac.th,.github.io node build.mjs   (the game only runs on these hosts; a leading dot = any sub-domain)
   The normal build is protected: the game object is not on window, and the bundle is obfuscated (javascript-obfuscator)
   with settings chosen to keep the frame rate (no control-flow flattening or dead code). No source maps are written. */
