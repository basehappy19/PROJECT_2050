/* ---------- 1. shared engine: wrap each GDevelop module in a function so their top-level "return" guards work ---------- */
function writeEngine(){
  const files = fs.readdirSync(SHARED).filter(f => /^(1\d|2\d|3\d|4\d)-.*\.js$/.test(f)).sort();
  let code = "/* generated by build.mjs from src/engine — do not edit */\n";
  for (const f of files) code += `\n/* ---- ${f} ---- */\n(function(){\n${fs.readFileSync(path.join(SHARED, f), "utf8")}\n})();\n`;
  // 2.0: the multiplayer server runs the same rules (server/api/src/mp/engine.js loads this file into a sandbox)
  fs.writeFileSync(path.join(REPO, "server/api/src/mp/game-engine.js"), code.replace("/* generated by build.mjs from src/engine — do not edit */", "/* generated by web/build.mjs from web/src/engine for the multiplayer server — do not edit; it is read as text, not imported */"));
  code += "\nexport default window.P2050;\n";
  fs.mkdirSync(path.join(HERE, "src/gen"), {recursive:true});
  fs.writeFileSync(path.join(HERE, "src/gen/engine.js"), code);
  return files;
}

/* ---------- 2. icons: only the lucide icons the game uses ---------- */
function writeIcons(){
  const dir = path.join(HERE, "node_modules/lucide-static/icons");
  const avail = new Set(fs.readdirSync(dir).map(f => f.replace(/\.svg$/, "")));
  const used = new Set();
  const scan = txt => { for (const m of txt.matchAll(/["'`\[ ]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)["'`\]]/g)) if (avail.has(m[1])) used.add(m[1]); };
  for (const f of fs.readdirSync(SHARED)) if (f.endsWith(".js")) scan(fs.readFileSync(path.join(SHARED, f), "utf8"));
  const walk = d => { for (const f of fs.readdirSync(d, {withFileTypes:true})){ const p = path.join(d, f.name); if (f.isDirectory()){ if (f.name !== "gen") walk(p); } else if (/\.(jsx?|mjs)$/.test(f.name)) scan(fs.readFileSync(p, "utf8")); } };
  walk(path.join(HERE, "src"));
  const out = {};
  for (const n of [...used].sort()){
    const svg = fs.readFileSync(path.join(dir, n + ".svg"), "utf8");
    out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
  }
  fs.writeFileSync(path.join(HERE, "src/gen/icons.js"), "/* generated by build.mjs (lucide-static, ISC licence) */\nexport default " + JSON.stringify(out) + ";\n");
  return used.size;
}

/* ---------- 3. static media (images, audio, data) live directly in ../assets/; only fonts are copied in ---------- */
function copyDir(src, dst){
  fs.mkdirSync(dst, {recursive:true});
  for (const f of fs.readdirSync(src, {withFileTypes:true})){
    const s = path.join(src, f.name), d = path.join(dst, f.name);
    if (f.isDirectory()) copyDir(s, d);
    else if (!fs.existsSync(d) || fs.statSync(d).mtimeMs < fs.statSync(s).mtimeMs || fs.statSync(d).size !== fs.statSync(s).size) fs.copyFileSync(s, d);
  }
}
function fonts(){
  const dst = path.join(ASSETS, "fonts"); fs.mkdirSync(dst, {recursive:true});
  const pick = [
    ["kanit", "kanit", [500, 600, 700]],
    ["ibm-plex-sans-thai", "ibm-plex-sans-thai", [400, 600]],
    ["ibm-plex-mono", "ibm-plex-mono", [500, 600]],
    ["chakra-petch", "chakra-petch", [600, 700]],
  ];
  let css = "";
  const FAM = {"kanit":"Kanit", "ibm-plex-sans-thai":"IBM Plex Sans Thai", "ibm-plex-mono":"IBM Plex Mono", "chakra-petch":"Chakra Petch"};
  const RANGES = {thai:"U+02D7, U+0303, U+0331, U+0E01-0E5B, U+200C-200D, U+25CC", latin:"U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD"};
  for (const [pkg, file, weights] of pick){
    for (const w of weights) for (const sub of ["thai", "latin"]){
      const src = path.join(HERE, `node_modules/@fontsource/${pkg}/files/${file}-${sub}-${w}-normal.woff2`);
      if (!fs.existsSync(src)) continue;
      const name = `${file}-${sub}-${w}.woff2`;
      fs.copyFileSync(src, path.join(dst, name));
      css += `@font-face{font-family:"${FAM[pkg]}";font-style:normal;font-weight:${w};font-display:swap;src:url(fonts/${name}) format("woff2");unicode-range:${RANGES[sub]};}\n`;
    }
  }
  return css;
}

