const API = () => JSON.stringify(process.env.P2050_API || "").slice(1, -1);
const SW_REGISTER = `<script>
  // offline play: the service worker lives next to this page (not in game/)
  if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
    window.addEventListener("load", () => navigator.serviceWorker.register(new URL("sw.js", location.href)).catch(() => {}));
  }
</script>`;

export function buildWeb(exportDir, repo){
  const gameDir = path.join(repo, "game");
  fs.rmSync(gameDir, {recursive:true, force:true});
  fs.cpSync(exportDir, gameDir, {recursive:true});
  // root index.html = the export's page, loading every file from game/
  let html = fs.readFileSync(path.join(exportDir, "index.html"), "utf8");
  html = html.replace(/<html>/, '<html lang="th">')
    .replace(/<meta charset="UTF-8"\/>/, `<meta charset="UTF-8"/>\n    <base href="game/">`)
    .replace(/\s*<link rel="manifest" href="manifest.webmanifest">/, "")
    .replace(/<meta name="theme-color" content="#000000" \/>/, `<meta name="theme-color" content="#061015" />\n${HEAD.replace("__API__", API())}`)
    .replace(/background-color: #000000;/, "background-color: #061015;")
    .replace(/<\/body>/, `${SW_REGISTER}\n</body>`);
  fs.writeFileSync(path.join(repo, "index.html"), html);
  // service worker: precache the page, icons and the whole game/ folder; version = hash of the file list
  const files = [];
  const walk = d => { for (const f of fs.readdirSync(path.join(gameDir, d))){ const rel = d ? `${d}/${f}` : f; if (fs.statSync(path.join(gameDir, rel)).isDirectory()) walk(rel); else files.push({f:`game/${rel}`, s:fs.statSync(path.join(gameDir, rel)).size, h:crypto.createHash("md5").update(fs.readFileSync(path.join(gameDir, rel))).digest("hex").slice(0, 8)}); } };
  walk("");
  const ver = crypto.createHash("sha1").update(files.map(x => x.f + x.h).join("|") + html).digest("hex").slice(0, 10);
  const core = ["./", "index.html", "site.webmanifest", "favicon.svg", "icon-16.png", "icon-32.png", "icon-192.png", "icon-512.png", "apple-touch-icon.png"];
  const sw = `/* Project : 2050 — service worker (offline play). Generated by gdevelop/_source/build/build-web.mjs; do not edit by hand. */
const CACHE = "p2050-v2-${ver}";
const FILES = ${JSON.stringify([...core, ...files.map(x => x.f)])};

self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => Promise.all(FILES.map(f => c.add(f).catch(() => {})))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith("p2050-") && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
/* Audio elements send Range requests; answer them from the cached file with a 206 slice. */
async function rangeResponse(req, res){
  const m = /bytes=(\\d*)-(\\d*)/.exec(req.headers.get("range") || ""); if (!m) return res;
  const buf = await res.arrayBuffer(), size = buf.byteLength;
  const start = m[1] ? +m[1] : Math.max(0, size - +m[2]), end = m[1] && m[2] ? Math.min(+m[2], size - 1) : size - 1;
  return new Response(buf.slice(start, end + 1), {status:206, statusText:"Partial Content", headers:{
    "Content-Type":res.headers.get("Content-Type") || "audio/mpeg", "Content-Range":\`bytes \${start}-\${end}/\${size}\`, "Content-Length":String(end - start + 1), "Accept-Ranges":"bytes"}});
}
self.addEventListener("fetch", e => {
  const req = e.request; if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  if (/\\/(api|verify)\\//.test(url.pathname)) return;          // the game server is never cached
  if (req.mode === "navigate"){
    e.respondWith((async () => {
      try { const ctl = new AbortController(), tm = setTimeout(() => ctl.abort(), 4000); const r = await fetch(req, {signal:ctl.signal}); clearTimeout(tm); if (r.ok) (await caches.open(CACHE)).put("index.html", r.clone()); return r; }
      catch { return (await caches.match("index.html")) || (await caches.match("./")) || Response.error(); }
    })());
    return;
  }
  e.respondWith((async () => {
    const key = new Request(url.href.split("#")[0].split("?")[0]);
    const hit = await caches.match(key, {ignoreSearch:true});
    if (hit) return req.headers.has("range") ? rangeResponse(req, hit) : hit;
    try { const r = await fetch(req); if (r.ok && r.status === 200){ const cp = r.clone(); caches.open(CACHE).then(c => c.put(key, cp)); } return r; }
    catch { return Response.error(); }
  })());
});
`;
  fs.writeFileSync(path.join(repo, "sw.js"), sw);
  console.log(`web version: index.html + game/ (${files.length} files) + sw.js (${ver})`);
}
